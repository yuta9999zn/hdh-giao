# ===== Nguồn 'hợp ngữ văn bản' — VÒNG LẶP HỘI TỤ CDFL có nhãn =====
#  TÁC_TỬ 0 ; nhãn L ; HỌC 0 ; GIAO 0 ; RỌI 0 ; NHẢY_ĐỘNG L ; DỪNG 0
SRC = "T00:LH00G00R00J@LD00$"
ram = [0]*256
for i, ch in enumerate(SRC): ram[i] = ord(ch)
ram[250] = 0     # ip
ram[251] = 0     # op tạm
ram[252] = 0     # icount
ram[253] = 100   # out

if __name__ == "__main__":
    print("="*68)
    print("ASSEMBLER MỨC 3 (136 lệnh gõ tay) — xác minh đầu/cuối bằng disasm")
    print("="*68)
    for i in (0,1,5,9,62,69,86,98,117,118,133,134,135):
        print(f"  {i:3d}:  {disasm_word(ASM3[i])}")
    print(f"  ... (tổng {len(ASM3)} lệnh)")

    print("\n" + "="*68)
    print(f"HỢP DỊCH nguồn có nhãn:  {SRC!r}")
    print("="*68)
    m = GVM(ASM3, world={}, ram=ram)
    m.run()
    icount = m.ram[252]
    out = m.ram[100:100+icount]
    print(f"  Bảng nhãn: L = {m.ram[211]}   (RAM[211])")
    print(f"  Sinh {icount} lệnh, RAM ra [100..]: {out}")
    for k, word in enumerate(out):
        print(f"     {100+k}:  {word:5d}  →  {disasm_word(word)}")

    print("\n" + "="*68)
    print("ĐÓNG VÒNG: chạy chương trình CÓ VÒNG LẶP vừa hợp dịch (world vật0=37)")
